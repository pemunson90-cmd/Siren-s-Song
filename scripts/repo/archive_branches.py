#!/usr/bin/env python3
"""Plan, and with the owner's approval carry out, the archiving of old branches.

It reads the branch ledger (`.fable/BRANCH_LEDGER.md`, produced by
`branch_ledger.py`) and takes every branch classed MERGED or UNMERGED-STALE.
For each one the plan is: create the tag `archive/branch/<name>` at the
branch tip, push the tag, and only then remove the branch ref on the remote.
The tag keeps every commit reachable, so nothing is lost.

  archive_branches.py --dry-run
      Print the plan as Markdown. Changes nothing. This is the default.
  archive_branches.py --execute --approved-by-pat
      Create and push the tags. Removes no branch.
  archive_branches.py --remove-branches --approved-by-pat
      Remove the remote ref of each planned branch, but only where the remote
      already holds the archive tag at the same commit as the branch tip.

Without `--approved-by-pat` the two changing modes refuse to run: executing
the archive plan is the repository owner's decision. An agent run never
passes that flag.
"""
import argparse
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
ARCHIVABLE = ("MERGED", "UNMERGED-STALE")
HEADING = re.compile(r"^## ([A-Z-]+) \(\d+\)")
ROW = re.compile(r"^\| `([^`]+)` \| ([0-9a-f]{7,40}) \|")


def git(*args, check=True):
    return subprocess.run(["git", "-C", str(ROOT), *args], capture_output=True, text=True, check=check)


def plan(ledger):
    rows, section = [], ""
    for line in ledger.read_text(encoding="utf-8").splitlines():
        heading = HEADING.match(line)
        if heading:
            section = heading.group(1)
            continue
        row = ROW.match(line)
        if row and section in ARCHIVABLE:
            rows.append((section, row.group(1), row.group(2)))
    return rows


def print_plan(rows, remote, ledger):
    counts = {name: sum(1 for row in rows if row[0] == name) for name in ARCHIVABLE}
    print("# Branch archive plan\n")
    print("Status: GENERATED by `python scripts/repo/archive_branches.py --dry-run` from `%s`. Nothing was changed.\n" % ledger.relative_to(ROOT).as_posix())
    print("%d branches would be archived: %d MERGED (the tip is already in `main` or `claude/integration`) and %d UNMERGED-STALE (old, unmerged; the tag keeps the tip). Branches classed SHARED, ACTIVE or UNMERGED-UNIQUE are not touched.\n" % (len(rows), counts["MERGED"], counts["UNMERGED-STALE"]))
    print("For each branch: create tag `archive/branch/<name>` at the tip, push the tag to `%s`, then remove the branch ref. A tag holds every commit of the branch, so the history stays reachable and a branch can be recreated from its tag at any time.\n" % remote)
    print("Commands for Pat (or a later session with his approval), run from the repository root. The first three lines refresh the ledger, because branches change class as they age and as pull requests open and close:\n")
    print("```\ngit fetch --all\ngh pr list --state all --limit 1000 --json number,state,headRefName,baseRefName > prs.json\npython scripts/repo/branch_ledger.py --prs prs.json > .fable/BRANCH_LEDGER.md\npython scripts/repo/archive_branches.py --execute --approved-by-pat\npython scripts/repo/archive_branches.py --remove-branches --approved-by-pat\n```\n")
    print("The `--execute` command only adds tags. The `--remove-branches` command removes a branch only where the remote already has its archive tag at the same commit.\n")
    print("| Class | Branch | Tip | Tag that would be created |")
    print("| --- | --- | --- | --- |")
    for section, name, tip in rows:
        print("| %s | `%s` | %s | `archive/branch/%s` |" % (section, name, tip, name))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--dry-run", action="store_true", help="print the plan and change nothing (default)")
    mode.add_argument("--execute", action="store_true", help="create and push the archive tags")
    mode.add_argument("--remove-branches", action="store_true", help="remove remote branch refs that already have a pushed archive tag")
    parser.add_argument("--approved-by-pat", action="store_true", help="required for --execute and --remove-branches")
    parser.add_argument("--remote", default="origin")
    parser.add_argument("--ledger", default=str(ROOT / ".fable" / "BRANCH_LEDGER.md"))
    args = parser.parse_args()
    ledger = pathlib.Path(args.ledger).resolve()
    rows = plan(ledger)
    if not (args.execute or args.remove_branches):
        print_plan(rows, args.remote, ledger)
        return 0
    if not args.approved_by_pat:
        print("Refused: executing the archive plan is the owner's decision. Pass --approved-by-pat only on Pat's instruction.", file=sys.stderr)
        return 2
    failures = 0
    for section, name, tip in rows:
        tag = "archive/branch/" + name
        ref = "refs/remotes/%s/%s" % (args.remote, name)
        current = git("rev-parse", "--verify", "--quiet", ref, check=False).stdout.strip()
        if not current:
            print("skip %s: branch no longer on %s" % (name, args.remote))
            continue
        if not current.startswith(tip):
            print("skip %s: tip moved since the ledger was written (%s, ledger %s); refresh the ledger" % (name, current[:8], tip))
            continue
        if args.execute:
            if not git("rev-parse", "--verify", "--quiet", "refs/tags/" + tag, check=False).stdout.strip():
                git("tag", tag, current)
            pushed = git("push", args.remote, "refs/tags/%s:refs/tags/%s" % (tag, tag), check=False)
            print(("tagged %s" if pushed.returncode == 0 else "FAILED to push tag for %s") % name)
            failures += pushed.returncode != 0
        else:
            remote_tag = git("ls-remote", args.remote, "refs/tags/" + tag, check=False).stdout.split()
            if not remote_tag or remote_tag[0] != current:
                print("skip %s: %s does not hold tag %s at %s" % (name, args.remote, tag, current[:8]))
                continue
            removed = git("push", args.remote, ":refs/heads/" + name, check=False)
            print(("removed branch %s (kept as tag %s)" if removed.returncode == 0 else "FAILED to remove %s (tag %s exists)") % (name, tag))
            failures += removed.returncode != 0
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
